/// Initializes a pre-populated limit order book ready for market simulation.
pub fn create_order_book() -> LimitOrderBook {
    let mut bids: Bids = BTreeMap::new();
    let mut asks: Asks = BTreeMap::new();
    let mut index: Index = BTreeMap::new();

    // 1. Populate Bids (Buy orders resting below the market price, e.g., $98.50 to $99.50)
    let initial_bids = vec![
        Order {
            id: Id(1),
            price: Price(9950),
            quantity: Quantity(10),
            side: Side::Buy,
        },
        Order {
            id: Id(2),
            price: Price(9950),
            quantity: Quantity(25),
            side: Side::Buy,
        },
        Order {
            id: Id(3),
            price: Price(9900),
            quantity: Quantity(50),
            side: Side::Buy,
        },
        Order {
            id: Id(4),
            price: Price(9850),
            quantity: Quantity(100),
            side: Side::Buy,
        },
    ];

    for order in initial_bids {
        let price_val = order.price.0;
        let id_val = order.id.0;
        index.insert(id_val, (Side::Buy, price_val));
        bids.entry(Reverse(price_val))
            .or_insert_with(VecDeque::new)
            .push_back(order);
    }

    // 2. Populate Asks (Sell orders resting above the market price, e.g., $100.50 to $102.00)
    // Note: Best Ask (10050) must remain strictly higher than Best Bid (9950) to maintain a valid spread.
    let initial_asks = vec![
        Order {
            id: Id(5),
            price: Price(10050),
            quantity: Quantity(15),
            side: Side::Sell,
        },
        Order {
            id: Id(6),
            price: Price(10100),
            quantity: Quantity(30),
            side: Side::Sell,
        },
        Order {
            id: Id(7),
            price: Price(10100),
            quantity: Quantity(20),
            side: Side::Sell,
        },
        Order {
            id: Id(8),
            price: Price(10200),
            quantity: Quantity(80),
            side: Side::Sell,
        },
    ];

    for order in initial_asks {
        let price_val = order.price.0;
        let id_val = order.id.0;
        index.insert(id_val, (Side::Sell, price_val));
        asks.entry(price_val)
            .or_insert_with(VecDeque::new)
            .push_back(order);
    }

    LimitOrderBook { bids, asks, index }
}

pub fn return_trades(
    mut order_book: LimitOrderBook,
    order: Order,
) -> Result<Vec<Trade>, BookError> {
    order_book.add_order(order)
}

pub fn trades_to_spots(trades: &[Trade]) -> Vec<Spot> {
    trades
        .iter()
        .map(|trade| Spot(trade.price.0 as f64 / 100.0))
        .collect()
}

/// Creates an OptionEngine evaluating a sample option leg against each trade price.
pub fn create_option_engine(spots: &[Spot]) -> Result<OptionEngine, EngineError> {
    // Build a sample option leg (e.g., Long Call with Strike 100.0 and Premium 3.0)
    let sample_leg = OptionLeg::build(
        OptionKind::Call,
        quant_core::payoffs::types::Side::Long,
        Strike(100.0),
        Premium(3.0),
    )
    .expect("Invalid OptionLeg parameters");

    // Replicate the leg for each spot price generated by the order book matching
    let legs = vec![sample_leg; spots.len()];

    OptionEngine::build(&legs, spots)
}

/// Creates a SpreadEngine evaluating a Bull Call Spread against each trade price.
pub fn create_spread_engine(spots: &[Spot]) -> Result<SpreadEngine<BullCallSpread>, EngineError> {
    // Build a sample Bull Call Spread (e.g., Strike low = 99.0, Strike up = 102.0)
    let sample_spread = BullCallSpread::build(
        Strike(102.0), // strike_up
        Strike(99.0),  // strike_down
        Premium(0.5),  // premium_up
        Premium(2.0),  // premium_down
        quant_core::payoffs::types::Side::Long,
    )
    .expect("Invalid BullCallSpread parameters");

    // Replicate the spread for each spot price generated by the order book matching
    let spreads = vec![sample_spread; spots.len()];

    SpreadEngine::build(&spreads, spots)
}

/// Creates a VolatilityEngine evaluating a Straddle strategy against each trade price.
pub fn create_volatility_engine(spots: &[Spot]) -> Result<VolatilityEngine<Straddle>, EngineError> {
    // Build a sample Straddle (e.g., Strike at 100.0, Call Premium 3.0, Put Premium 3.0, Long position)
    let sample_straddle = Straddle::build(
        Strike(100.0),                          // strike
        Premium(3.0),                           // call_premium
        Premium(3.0),                           // put_premium
        quant_core::payoffs::types::Side::Long, // position
    )
    .expect("Invalid Straddle parameters");

    // Replicate the straddle for each spot price generated by the order book matching
    let straddles = vec![sample_straddle; spots.len()];

    VolatilityEngine::build(&straddles, spots)
}

/// Creates a RangeEngine evaluating an Iron Condor strategy against each trade price.
pub fn create_range_engine(spots: &[Spot]) -> Result<RangeEngine<IronCondor>, EngineError> {
    // Build a sample Iron Condor with valid strikes and premiums
    let sample_condor = IronCondor::build(
        Strike(70.0),  // long_put_strike
        Premium(2.0),  // long_put_premium
        Strike(80.0),  // short_put_strike
        Premium(3.0),  // short_put_premium
        Strike(90.0),  // short_call_strike
        Premium(4.0),  // short_call_premium
        Strike(100.0), // long_call_strike
        Premium(5.0),  // long_call_premium
    )
    .expect("Invalid IronCondor parameters");

    // Replicate the Iron Condor for each spot price generated by the order book matching
    let condors = vec![sample_condor; spots.len()];

    RangeEngine::build(&condors, spots)
}

